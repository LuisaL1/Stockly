-- =====================================================================
-- Stockly v3: sucursales, auditoría de movimientos, inteligencia de rotación
-- y permisos de Novandra.
--
--  * Sucursales: sedes que agrupan bodegas. Límite por plan.
--  * Auditoría: registro inalterable de quién hizo qué (ventas, anulaciones,
--    salidas manuales, movimientos borrados, cambios de precio y de stock,
--    traslados, órdenes). Solo lo ven el dueño y los administradores.
--  * Rotación: estadísticas por producto calculadas contra la propia empresa
--    (lo "normal" de cada negocio), pronóstico de demanda y alertas.
--  * novandra_config: lo que el dueño autoriza a Novandra.
-- Requiere las migraciones v2, registro y seguridad.
-- =====================================================================

-- ---------------------------------------------------------------------
-- Sucursales
-- ---------------------------------------------------------------------
create table if not exists public.sucursales (
  id bigint generated by default as identity primary key,
  id_empresa bigint not null references public."Empresa"(id) on delete cascade,
  nombre text not null,
  ciudad text,
  direccion text,
  telefono text,
  responsable text,
  activa boolean not null default true,
  created_at timestamptz not null default now(),
  unique (id_empresa, nombre)
);

alter table public.bodegas add column if not exists id_sucursal bigint references public.sucursales(id) on delete set null;
alter table public.stockly_planes add column if not exists limite_sucursales int;
update public.stockly_planes set limite_sucursales = case id when 'basico' then 1 when 'pro' then 3 else null end;

alter table public.sucursales enable row level security;
drop policy if exists "miembros sucursales" on public.sucursales;
create policy "miembros sucursales" on public.sucursales for select using (public.stockly_es_miembro(id_empresa));
drop policy if exists "admins sucursales" on public.sucursales;
create policy "admins sucursales" on public.sucursales for all
  using (public.stockly_es_admin(id_empresa)) with check (public.stockly_es_admin(id_empresa));

-- Cada empresa tiene una sede principal; sus bodegas sin sede quedan en ella.
create or replace function public.stockly_inicializar_sucursal(_id_empresa bigint)
returns bigint
language plpgsql security definer set search_path = public
as $$
declare _id bigint;
begin
  select id into _id from sucursales where id_empresa = _id_empresa order by id limit 1;
  if _id is null then
    insert into sucursales (id_empresa, nombre, ciudad)
    select _id_empresa, 'Sede principal', e.ciudad from "Empresa" e where e.id = _id_empresa
    returning id into _id;
  end if;
  update bodegas set id_sucursal = _id where id_empresa = _id_empresa and id_sucursal is null;
  return _id;
end $$;

create or replace function public.tg_bodegas_sucursal()
returns trigger language plpgsql security definer set search_path = public
as $$
begin
  if new.id_sucursal is null then
    new.id_sucursal := (select id from sucursales where id_empresa = new.id_empresa order by id limit 1);
  end if;
  return new;
end $$;
drop trigger if exists bodegas_sucursal on public.bodegas;
create trigger bodegas_sucursal before insert on public.bodegas
  for each row execute function public.tg_bodegas_sucursal();

create or replace function public.tg_empresa_sucursal()
returns trigger language plpgsql security definer set search_path = public
as $$
begin
  perform public.stockly_inicializar_sucursal(new.id);
  return new;
end $$;
-- Corre después de crear la bodega principal (orden alfabético de triggers: empresa_inicializar < empresa_sucursal).
drop trigger if exists empresa_sucursal on public."Empresa";
create trigger empresa_sucursal after insert on public."Empresa"
  for each row execute function public.tg_empresa_sucursal();

select public.stockly_inicializar_sucursal(id) from public."Empresa";

create or replace function public.tg_sucursales_limite()
returns trigger language plpgsql security definer set search_path = public
as $$
declare _limite int;
begin
  _limite := (public.stockly_plan(new.id_empresa)).limite_sucursales;
  if _limite is not null and (select count(*) from sucursales where id_empresa = new.id_empresa) >= _limite then
    raise exception 'Tu plan permite % sucursal(es). Mejora tu plan para agregar más.', _limite;
  end if;
  return new;
end $$;
drop trigger if exists sucursales_limite on public.sucursales;
create trigger sucursales_limite before insert on public.sucursales
  for each row execute function public.tg_sucursales_limite();

-- ---------------------------------------------------------------------
-- Auditoría (solo inserción, desde triggers)
-- ---------------------------------------------------------------------
create table if not exists public.auditoria (
  id bigint generated by default as identity primary key,
  id_empresa bigint not null references public."Empresa"(id) on delete cascade,
  id_usuario bigint,            -- quién lo hizo realmente (usuario en sesión)
  usuario_nombre text,          -- nombre en ese momento
  accion text not null,
  entidad text not null,
  id_entidad bigint,
  id_producto bigint,
  id_bodega bigint references public.bodegas(id) on delete set null,
  id_sucursal bigint references public.sucursales(id) on delete set null,
  cantidad numeric,
  detalle jsonb not null default '{}'::jsonb,
  alerta text,                  -- motivo si el movimiento es sospechoso
  fecha timestamptz not null default now()
);
create index if not exists auditoria_empresa_fecha on public.auditoria (id_empresa, fecha desc);
create index if not exists auditoria_usuario on public.auditoria (id_empresa, id_usuario, fecha desc);

alter table public.auditoria enable row level security;
drop policy if exists "admins auditoria" on public.auditoria;
create policy "admins auditoria" on public.auditoria for select using (public.stockly_es_admin(id_empresa));
-- Sin políticas de insert/update/delete: nadie puede alterar el registro desde la app.

create or replace function public.stockly_auditar(
  _id_empresa bigint, _accion text, _entidad text, _id_entidad bigint, _detalle jsonb,
  _id_producto bigint default null, _id_bodega bigint default null, _cantidad numeric default null, _alerta text default null)
returns void
language plpgsql security definer set search_path = public
as $$
declare
  _actor bigint := public.stockly_id_usuario();
  _hora int := extract(hour from now() at time zone 'America/Bogota');
begin
  if _id_empresa is null then return; end if;
  -- Fuera de horario (antes de 6 a. m. o desde las 10 p. m.) se marca para revisión.
  if _alerta is null and _actor is not null and (_hora < 6 or _hora >= 22) then
    _alerta := 'Fuera de horario';
  end if;
  insert into auditoria (id_empresa, id_usuario, usuario_nombre, accion, entidad, id_entidad, id_producto, id_bodega,
                         id_sucursal, cantidad, detalle, alerta)
  values (_id_empresa, _actor, (select nullif(nombres, '') from "Usuarios" where id = _actor), _accion, _entidad,
          _id_entidad, _id_producto, _id_bodega, (select id_sucursal from bodegas where id = _id_bodega), _cantidad,
          coalesce(_detalle, '{}'::jsonb), _alerta);
end $$;
revoke execute on function public.stockly_auditar(bigint, text, text, bigint, jsonb, bigint, bigint, numeric, text) from public, anon, authenticated;

-- Kardex: solo los movimientos manuales (los de ventas, anulaciones y compras se auditan en su origen).
create or replace function public.tg_auditar_kardex()
returns trigger language plpgsql security definer set search_path = public
as $$
declare
  _fila record;
  _actor bigint := public.stockly_id_usuario();
  _alerta text;
begin
  if tg_op = 'DELETE' then _fila := old; else _fila := new; end if;
  if tg_op = 'INSERT' and coalesce(_fila.detalle, '') ~ '^(Venta |Anulación |Orden de compra )' then
    return null;
  end if;
  if tg_op = 'INSERT' and _actor is not null and _fila.id_usuario is distinct from _actor then
    _alerta := 'Registrado a nombre de otro usuario';
  elsif tg_op = 'DELETE' then
    _alerta := 'Movimiento eliminado';
  end if;
  perform public.stockly_auditar(
    _fila.id_empresa,
    case when tg_op = 'DELETE' then 'movimiento_eliminado'
         when lower(_fila.tipo) = 'salida' then 'salida_manual' else 'entrada_manual' end,
    'kardex', _fila.id,
    jsonb_build_object('tipo', _fila.tipo, 'detalle', _fila.detalle, 'fecha_movimiento', _fila.fecha,
                       'usuario_declarado', _fila.id_usuario,
                       'producto', (select descripcion from productos where id = _fila.id_producto)),
    _fila.id_producto, _fila.id_bodega, _fila.cantidad, _alerta);
  return null;
end $$;
drop trigger if exists auditar_kardex on public.kardex;
create trigger auditar_kardex after insert or delete on public.kardex
  for each row execute function public.tg_auditar_kardex();

create or replace function public.tg_auditar_ventas()
returns trigger language plpgsql security definer set search_path = public
as $$
begin
  if tg_op = 'INSERT' then
    perform public.stockly_auditar(new.id_empresa, 'venta', 'ventas', new.id,
      jsonb_build_object('factura', new.prefijo || '-' || new.numero, 'metodo_pago', new.metodo_pago, 'canal', new.canal),
      null, new.id_bodega, null);
  elsif new.estado = 'anulada' and old.estado <> 'anulada' then
    perform public.stockly_auditar(new.id_empresa, 'venta_anulada', 'ventas', new.id,
      jsonb_build_object('factura', new.prefijo || '-' || new.numero, 'total', new.total, 'nota', new.nota,
                         'vendida_por', new.id_usuario,
                         'vendedor', (select nombres from "Usuarios" where id = new.id_usuario)),
      null, new.id_bodega, null, 'Venta anulada');
  elsif new.total is distinct from old.total and old.total > 0 then
    -- Totales de una venta ya cerrada (registrar_venta los calcula una sola vez).
    perform public.stockly_auditar(new.id_empresa, 'venta_modificada', 'ventas', new.id,
      jsonb_build_object('factura', new.prefijo || '-' || new.numero, 'total_antes', old.total, 'total_despues', new.total,
                         'descuento', new.descuento),
      null, new.id_bodega, null, 'Total de venta modificado');
  elsif new.total is distinct from old.total and old.total = 0 and new.subtotal > 0 and new.descuento / new.subtotal > 0.2 then
    perform public.stockly_auditar(new.id_empresa, 'descuento_alto', 'ventas', new.id,
      jsonb_build_object('factura', new.prefijo || '-' || new.numero, 'subtotal', new.subtotal, 'descuento', new.descuento,
                         'porcentaje', round(new.descuento / new.subtotal * 100)),
      null, new.id_bodega, null, 'Descuento mayor al 20%');
  end if;
  return null;
end $$;
drop trigger if exists auditar_ventas on public.ventas;
create trigger auditar_ventas after insert or update on public.ventas
  for each row execute function public.tg_auditar_ventas();

create or replace function public.tg_auditar_productos()
returns trigger language plpgsql security definer set search_path = public
as $$
declare _cambios jsonb := '{}'::jsonb;
begin
  if tg_op = 'INSERT' then
    perform public.stockly_auditar(new.id_empresa, 'producto_creado', 'productos', new.id,
      jsonb_build_object('producto', new.descripcion, 'stock_inicial', new.stock, 'precio', new.precioventa), new.id, null, new.stock);
  elsif tg_op = 'DELETE' then
    perform public.stockly_auditar(old.id_empresa, 'producto_eliminado', 'productos', old.id,
      jsonb_build_object('producto', old.descripcion, 'stock', old.stock), old.id, null, old.stock, 'Producto eliminado');
  else
    if new.precioventa is distinct from old.precioventa then
      _cambios := _cambios || jsonb_build_object('precio_venta', jsonb_build_array(old.precioventa, new.precioventa));
    end if;
    if new.preciocompra is distinct from old.preciocompra then
      _cambios := _cambios || jsonb_build_object('precio_compra', jsonb_build_array(old.preciocompra, new.preciocompra));
    end if;
    if new.stock_minimo is distinct from old.stock_minimo then
      _cambios := _cambios || jsonb_build_object('stock_minimo', jsonb_build_array(old.stock_minimo, new.stock_minimo));
    end if;
    if _cambios <> '{}'::jsonb then
      perform public.stockly_auditar(new.id_empresa, 'producto_editado', 'productos', new.id,
        _cambios || jsonb_build_object('producto', new.descripcion), new.id, null, null,
        case when _cambios ? 'precio_venta' then 'Cambio de precio' end);
    end if;
    -- El stock solo debe cambiar por el kardex (trigger). Un cambio directo es sospechoso.
    if new.stock is distinct from old.stock and pg_trigger_depth() = 1 then
      perform public.stockly_auditar(new.id_empresa, 'stock_modificado_directo', 'productos', new.id,
        jsonb_build_object('producto', new.descripcion, 'antes', old.stock, 'despues', new.stock),
        new.id, null, new.stock - old.stock, 'Stock cambiado sin movimiento de kardex');
    end if;
  end if;
  return null;
end $$;
drop trigger if exists auditar_productos on public.productos;
create trigger auditar_productos after insert or update or delete on public.productos
  for each row execute function public.tg_auditar_productos();

