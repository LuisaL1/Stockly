-- ---------------------------------------------------------------- Ventas de mercancía en consignación
-- Cuando el partner vende un producto que tiene en consignación, la venta se reparte sobre las consignaciones
-- abiertas (la más antigua primero) y queda "por liquidar". Si la venta se anula, se revierte.
create or replace function public.tg_consignacion_venta()
returns trigger language plpgsql security definer set search_path = public
as $$
declare
  _v public.ventas;
  _c public.red_consignaciones;
  _resta numeric;
  _toma numeric;
begin
  if new.id_producto is null then return null; end if;
  select * into _v from ventas where id = new.id_venta;
  if not found or _v.estado = 'anulada' then return null; end if;
  _resta := new.cantidad;
  for _c in select * from red_consignaciones where id_partner = _v.id_empresa and id_producto = new.id_producto and cantidad - vendida - devuelta > 0 order by created_at, id loop
    exit when _resta <= 0;
    _toma := least(_resta, _c.cantidad - _c.vendida - _c.devuelta);
    insert into red_consignacion_ventas (id_consignacion, id_venta, id_detalle_venta, cantidad, precio_red, total)
    values (_c.id, _v.id, new.id, _toma, _c.precio_red, round(_toma * _c.precio_red, 2));
    update red_consignaciones set vendida = vendida + _toma where id = _c.id;
    _resta := _resta - _toma;
  end loop;
  return null;
end $$;
drop trigger if exists consignacion_venta on public.detalle_venta;
create trigger consignacion_venta after insert on public.detalle_venta for each row execute function public.tg_consignacion_venta();

create or replace function public.tg_consignacion_anulacion()
returns trigger language plpgsql security definer set search_path = public
as $$
declare _cv record;
begin
  if new.estado = 'anulada' and old.estado is distinct from 'anulada' then
    for _cv in select * from red_consignacion_ventas where id_venta = new.id and estado = 'pendiente' loop
      update red_consignaciones set vendida = greatest(vendida - _cv.cantidad, 0) where id = _cv.id_consignacion;
      update red_consignacion_ventas set estado = 'anulada' where id = _cv.id;
    end loop;
  end if;
  return null;
end $$;
drop trigger if exists consignacion_anulacion on public.ventas;
create trigger consignacion_anulacion after update of estado on public.ventas for each row execute function public.tg_consignacion_anulacion();

-- Resumen de consignación para la empresa (como partner o como matriz)
create or replace function public.stockly_red_consignacion(_id_empresa bigint)
returns jsonb language plpgsql stable security definer set search_path = public
as $$
begin
  if not public.stockly_es_miembro(_id_empresa) then raise exception 'Sin permiso'; end if;
  return jsonb_build_object(
    'productos', coalesce((select jsonb_agg(to_jsonb(x) order by x.otra, x.descripcion) from (
      select c.id_vinculo, case when c.id_partner = _id_empresa then 'partner' else 'matriz' end as mi_rol,
             case when c.id_partner = _id_empresa then m.nombre else p.nombre end as otra,
             c.id_producto, c.descripcion, c.precio_red,
             sum(c.cantidad) as recibida, sum(c.vendida) as vendida, sum(c.devuelta) as devuelta, sum(c.cantidad - c.vendida - c.devuelta) as disponible,
             coalesce((select sum(cv.total) from red_consignacion_ventas cv join red_consignaciones cc on cc.id = cv.id_consignacion
                        where cc.id_vinculo = c.id_vinculo and cc.id_producto = c.id_producto and cv.estado = 'pendiente'), 0) as por_liquidar
        from red_consignaciones c
        join "Empresa" m on m.id = c.id_matriz
        join "Empresa" p on p.id = c.id_partner
       where _id_empresa in (c.id_partner, c.id_matriz)
       group by c.id_vinculo, c.id_partner, c.id_matriz, m.nombre, p.nombre, c.id_producto, c.descripcion, c.precio_red) x), '[]'::jsonb),
    'por_liquidar', coalesce((select jsonb_agg(to_jsonb(x)) from (
      select c.id_vinculo, case when c.id_partner = _id_empresa then m.nombre else p.nombre end as otra,
             case when c.id_partner = _id_empresa then 'partner' else 'matriz' end as mi_rol,
             sum(cv.total) as total, sum(cv.cantidad) as unidades, count(*) as ventas
        from red_consignacion_ventas cv join red_consignaciones c on c.id = cv.id_consignacion
        join "Empresa" m on m.id = c.id_matriz join "Empresa" p on p.id = c.id_partner
       where cv.estado = 'pendiente' and _id_empresa in (c.id_partner, c.id_matriz)
       group by c.id_vinculo, c.id_partner, c.id_matriz, m.nombre, p.nombre) x), '[]'::jsonb),
    'liquidaciones', coalesce((select jsonb_agg(to_jsonb(x) order by x.created_at desc) from (
      select l.id, l.numero, l.total, l.unidades, l.estado, l.nota, l.created_at, l.pagada_en, l.id_vinculo,
             case when l.id_partner = _id_empresa then 'partner' else 'matriz' end as mi_rol,
             case when l.id_partner = _id_empresa then m.nombre else p.nombre end as otra
        from red_liquidaciones l join "Empresa" m on m.id = l.id_matriz join "Empresa" p on p.id = l.id_partner
       where _id_empresa in (l.id_partner, l.id_matriz) limit 200) x), '[]'::jsonb));
end $$;

-- El partner liquida lo vendido en consignación de un vínculo (queda pendiente de pago); la matriz la marca pagada.
create or replace function public.stockly_red_liquidar(_id_vinculo bigint, _id_empresa bigint, _nota text default null)
returns jsonb language plpgsql security definer set search_path = public
as $$
declare _v public.red_vinculos; _total numeric; _unid numeric; _id bigint; _numero int; _mi text;
begin
  if not public.stockly_es_admin(_id_empresa) then raise exception 'Solo el dueño o un administrador puede liquidar'; end if;
  _v := public.stockly_red_vinculo(_id_vinculo, _id_empresa);
  if _v.id_partner <> _id_empresa then raise exception 'Solo el partner liquida sus ventas en consignación'; end if;
  select coalesce(sum(cv.total), 0), coalesce(sum(cv.cantidad), 0) into _total, _unid
    from red_consignacion_ventas cv join red_consignaciones c on c.id = cv.id_consignacion
   where c.id_vinculo = _id_vinculo and cv.estado = 'pendiente';
  if _unid <= 0 then raise exception 'No hay ventas en consignación por liquidar'; end if;
  select coalesce(max(numero), 0) + 1 into _numero from red_liquidaciones where id_partner = _id_empresa;
  insert into red_liquidaciones (id_vinculo, id_partner, id_matriz, numero, total, unidades, nota, creado_por)
  values (_id_vinculo, _id_empresa, _v.id_matriz, _numero, _total, _unid, nullif(btrim(_nota), ''), public.stockly_id_usuario()) returning id into _id;
  update red_consignacion_ventas cv set estado = 'liquidada', id_liquidacion = _id
    from red_consignaciones c where c.id = cv.id_consignacion and c.id_vinculo = _id_vinculo and cv.estado = 'pendiente';
  select nombre into _mi from "Empresa" where id = _id_empresa;
  perform public.stockly_red_notificar(_v.id_matriz, _mi || ' liquidó su consignación LIQ-' || _numero, trim_scale(_unid) || ' unidades · ' || to_char(_total, 'FM999G999G999G999') || '. Márcala como pagada cuando recibas el dinero.');
  return jsonb_build_object('id', _id, 'numero', _numero, 'total', _total, 'unidades', _unid);
end $$;
create or replace function public.stockly_red_liquidacion_pagada(_id bigint, _id_empresa bigint)
returns void language plpgsql security definer set search_path = public
as $$
declare _l public.red_liquidaciones; _mi text;
begin
  if not public.stockly_es_admin(_id_empresa) then raise exception 'Solo el dueño o un administrador puede confirmar pagos'; end if;
  select * into _l from red_liquidaciones where id = _id and id_matriz = _id_empresa for update;
  if not found then raise exception 'Liquidación no encontrada'; end if;
  if _l.estado = 'pagada' then raise exception 'Ya está pagada'; end if;
  update red_liquidaciones set estado = 'pagada', pagada_en = now() where id = _id;
  select nombre into _mi from "Empresa" where id = _id_empresa;
  perform public.stockly_red_notificar(_l.id_partner, _mi || ' confirmó el pago de LIQ-' || _l.numero, 'Consignación al día.');
end $$;

-- ---------------------------------------------------------------- Reposición automática
create or replace function public.stockly_red_reposicion(_id_empresa bigint, _id_vinculo bigint)
returns jsonb language plpgsql stable security definer set search_path = public
as $$
declare _v public.red_vinculos;
begin
  _v := public.stockly_red_vinculo(_id_vinculo, _id_empresa);
  return coalesce((select jsonb_agg(to_jsonb(x) order by x.descripcion) from (
    select p.id as id_producto, coalesce(p.nombre_completo, p.descripcion) as descripcion, p.stock, p.stock_minimo, p.unidad, p.presentacion,
           coalesce(r.activo, false) as activo, r.cantidad,
           exists (select 1 from red_pedidos pe join red_pedidos_detalle d on d.id_pedido = pe.id
                    where pe.id_vinculo = _id_vinculo and pe.id_solicitante = _id_empresa and pe.estado in ('borrador', 'pendiente') and d.id_producto_solicitante = p.id) as pedido_abierto
      from productos p
      left join red_reposicion r on r.id_vinculo = _id_vinculo and r.id_producto = p.id
     where p.id_empresa = _id_empresa) x), '[]'::jsonb);
end $$;
create or replace function public.stockly_red_reposicion_config(_id_vinculo bigint, _id_empresa bigint, _id_producto bigint, _activo boolean, _cantidad numeric)
returns void language plpgsql security definer set search_path = public
as $$
declare _v public.red_vinculos;
begin
  if not public.stockly_es_admin(_id_empresa) then raise exception 'Solo el dueño o un administrador configura la reposición'; end if;
  _v := public.stockly_red_vinculo(_id_vinculo, _id_empresa);
  if not exists (select 1 from productos where id = _id_producto and id_empresa = _id_empresa) then raise exception 'Producto no encontrado'; end if;
  if coalesce(_cantidad, 0) <= 0 then raise exception 'Indica cuánto pedir'; end if;
  insert into red_reposicion (id_vinculo, id_empresa, id_producto, activo, cantidad) values (_id_vinculo, _id_empresa, _id_producto, coalesce(_activo, true), _cantidad)
  on conflict (id_vinculo, id_producto) do update set activo = excluded.activo, cantidad = excluded.cantidad;
end $$;

-- Al bajar del mínimo: pedido en borrador (sin tocar stock) si no hay uno abierto para ese producto y vínculo.
create or replace function public.tg_red_reposicion_auto()
returns trigger language plpgsql security definer set search_path = public
as $$
declare _r record; _id bigint; _numero int; _otra bigint; _otra_nombre text;
begin
  if coalesce(new.stock, 0) > coalesce(new.stock_minimo, 0) then return null; end if;
  for _r in select r.*, v.id_matriz, v.id_partner from red_reposicion r join red_vinculos v on v.id = r.id_vinculo
             where r.id_producto = new.id and r.activo and v.estado = 'activo' loop
    continue when exists (select 1 from red_pedidos pe join red_pedidos_detalle d on d.id_pedido = pe.id
                           where pe.id_vinculo = _r.id_vinculo and pe.id_solicitante = _r.id_empresa and pe.estado in ('borrador', 'pendiente') and d.id_producto_solicitante = new.id);
    _otra := case when _r.id_matriz = _r.id_empresa then _r.id_partner else _r.id_matriz end;
    select nombre into _otra_nombre from "Empresa" where id = _otra;
    select coalesce(max(numero), 0) + 1 into _numero from red_pedidos where id_solicitante = _r.id_empresa;
    insert into red_pedidos (id_vinculo, id_solicitante, id_proveedor, numero, estado, origen, nota)
    values (_r.id_vinculo, _r.id_empresa, _otra, _numero, 'borrador', 'automatico', 'Reposición automática: ' || coalesce(new.nombre_completo, new.descripcion) || ' bajó del mínimo')
    returning id into _id;
    insert into red_pedidos_detalle (id_pedido, id_producto_solicitante, descripcion, codigointerno, codigobarras, cantidad)
    values (_id, new.id, coalesce(new.nombre_completo, new.descripcion), new.codigointerno::text, new.codigobarras::text, _r.cantidad);
    insert into notificaciones (id_empresa, tipo, titulo, mensaje, enlace)
    values (_r.id_empresa, 'red', 'Pedido automático listo para confirmar', coalesce(new.nombre_completo, new.descripcion) || ' bajó del mínimo. Pedido RED-' || _numero || ' a ' || _otra_nombre || ' en borrador: confírmalo en Red de empresas.', '/red');
  end loop;
  return null;
end $$;
drop trigger if exists red_reposicion_auto on public.productos;
create trigger red_reposicion_auto after update of stock on public.productos for each row execute function public.tg_red_reposicion_auto();

-- Confirmar un pedido en borrador (pasa a pendiente y la otra empresa lo ve)
create or replace function public.stockly_red_confirmar_pedido(_id_pedido bigint, _id_empresa bigint)
returns void language plpgsql security definer set search_path = public
as $$
declare _p public.red_pedidos; _mi text;
begin
  if not public.stockly_es_miembro(_id_empresa) then raise exception 'Sin permiso'; end if;
  select * into _p from red_pedidos where id = _id_pedido and id_solicitante = _id_empresa for update;
  if not found then raise exception 'Pedido no encontrado'; end if;
  if _p.estado <> 'borrador' then raise exception 'El pedido ya está %', _p.estado; end if;
  update red_pedidos set estado = 'pendiente' where id = _id_pedido;
  select nombre into _mi from "Empresa" where id = _id_empresa;
  perform public.stockly_red_notificar(_p.id_proveedor, 'Pedido de ' || _mi, 'Pedido RED-' || _p.numero || ' con ' || (select count(*) from red_pedidos_detalle where id_pedido = _id_pedido) || ' producto(s). Atiéndelo en Red de empresas.');
end $$;

