-- Red de empresas: consignación, pedidos automáticos y pedidos en borrador.
--  - Envío con modalidad "traslado" (sin cobro) o "consignacion": cada línea lleva un precio de red. Al
--    recibir en consignación, el partner lleva cuenta de lo recibido; cuando lo vende, esa venta queda
--    separada como "por liquidar a la matriz" y se liquida en bloque (la matriz la marca pagada).
--  - Pedido automático: el partner marca productos para reposición; cuando el stock baja del mínimo se crea
--    un pedido en borrador (no toca stock). El partner lo confirma, la matriz despacha, el stock solo cambia
--    al recibir.
--  - El plan Partner beneficia solo a la matriz; los partners conservan su propio plan.
-- Idempotente.

