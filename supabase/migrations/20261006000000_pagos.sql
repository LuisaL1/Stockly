-- =====================================================================
-- Stockly v3.1: medios de pago y links de pago con Wompi.
--
--  * pagos_venta: cada venta puede pagarse con uno o varios medios
--    (efectivo con cambio, datáfono con aprobación, transferencia, Nequi,
--    Daviplata, link de pago Wompi, crédito).
--  * Datos bancarios en la configuración de facturación.
--  * Credenciales de Wompi en una tabla que la app no puede leer: solo las
--    usan las Edge Functions (wompi-link y wompi-webhook).
--  * registrar_pago: abonos posteriores (crédito, transferencias que llegan después).
-- Requiere las migraciones anteriores.
-- =====================================================================

