    select conname from pg_constraint
     where conrelid = 'public.ventas'::regclass and contype = 'c' and pg_get_constraintdef(oid) ilike '%metodo_pago%'
  loop
    execute format('alter table public.ventas drop constraint %I', _c.conname);
  end loop;
end $$;
