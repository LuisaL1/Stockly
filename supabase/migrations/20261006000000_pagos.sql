create table if not exists public.pagos_venta (
  id bigint generated by default as identity primary key,
  id_venta bigint not null references public.ventas(id) on delete cascade,
  id_empresa bigint not null references public."Empresa"(id) on delete cascade,
  metodo text not null check (metodo in ('efectivo', 'tarjeta', 'datafono', 'transferencia', 'nequi', 'daviplata', 'link_pago', 'credito')),
  monto numeric(14, 2) not null check (monto > 0),
  recibido numeric(14, 2),          -- efectivo entregado por el cliente
  cambio numeric(14, 2),
  referencia text,                  -- n.º de aprobación del datáfono, referencia de la transferencia o id de Wompi
  franquicia text,                  -- Visa, Mastercard...
  banco text,
  estado text not null default 'aprobado' check (estado in ('aprobado', 'pendiente', 'rechazado', 'anulado')),
  link_id text,
  link_url text,
  id_usuario bigint,
  created_at timestamptz not null default now(),
  confirmado_en timestamptz
);
create index if not exists pagos_venta_venta on public.pagos_venta (id_venta);
create unique index if not exists pagos_venta_link on public.pagos_venta (link_id) where link_id is not null;

