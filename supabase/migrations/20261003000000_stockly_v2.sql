create or replace function public.trasladar_stock(
  _id_producto bigint, _id_origen bigint, _id_destino bigint, _cantidad numeric, _nota text default null)
returns void
language plpgsql security definer set search_path = public
as $$
declare
  _empresa bigint;
  _tipo_origen text;
  _tipo_destino text;
begin
  select id_empresa, tipo into _empresa, _tipo_origen from public.bodegas where id = _id_origen;
  select tipo into _tipo_destino from public.bodegas where id = _id_destino and id_empresa = _empresa;
  if _empresa is null or _tipo_destino is null or not public.stockly_es_miembro(_empresa) then
    raise exception 'Bodegas no válidas';
  end if;
  if _id_origen = _id_destino then raise exception 'Elige dos bodegas distintas'; end if;
  if _cantidad <= 0 then raise exception 'La cantidad debe ser mayor que cero'; end if;
  if public.stockly_disponible(_id_origen, _id_producto) < _cantidad then
    raise exception 'No hay stock suficiente en la bodega de origen (disponible: %)',
      trim_scale(public.stockly_disponible(_id_origen, _id_producto));
  end if;

  if _tipo_origen <> 'principal' then
    update public.stock_bodega set cantidad = cantidad - _cantidad
     where id_bodega = _id_origen and id_producto = _id_producto;
  end if;
  if _tipo_destino <> 'principal' then
    insert into public.stock_bodega (id_bodega, id_producto, cantidad) values (_id_destino, _id_producto, _cantidad)
    on conflict (id_bodega, id_producto) do update set cantidad = public.stock_bodega.cantidad + excluded.cantidad;
  end if;

  insert into public.traslados (id_empresa, id_producto, id_origen, id_destino, cantidad, id_usuario, nota)
  values (_empresa, _id_producto, _id_origen, _id_destino, _cantidad, public.stockly_id_usuario(), _nota);
end $$;

-- ---------------------------------------------------------------------
-- Ventas y facturas
-- ---------------------------------------------------------------------
-- _venta: { id_empresa, id_bodega, id_cliente?, canal, metodo_pago, estado?, nota?,
--           items: [{ id_producto, cantidad, precio_unitario, descuento?, iva? }] }
create or replace function public.registrar_venta(_venta jsonb)
returns jsonb
language plpgsql security definer set search_path = public
as $$
declare
  _empresa bigint := (_venta->>'id_empresa')::bigint;
  _bodega bigint := (_venta->>'id_bodega')::bigint;
  _usuario bigint := public.stockly_id_usuario();
  _plan public.stockly_planes;
  _cfg public.config_facturacion;
  _item jsonb;
  _producto record;
  _cantidad numeric;
  _precio numeric;
  _desc numeric;
  _iva numeric;
  _base numeric;
  _subtotal numeric := 0;
  _descuento numeric := 0;
  _impuesto numeric := 0;
  _id_venta bigint;
  _numero int;
  _ventas_mes int;
begin
  if not public.stockly_es_miembro(_empresa) then raise exception 'Sin acceso a esta empresa'; end if;
  if not exists (select 1 from public.bodegas where id = _bodega and id_empresa = _empresa and activa) then
    raise exception 'Bodega no válida';
  end if;
  if jsonb_array_length(coalesce(_venta->'items', '[]'::jsonb)) = 0 then
    raise exception 'La venta no tiene productos';
  end if;

  _plan := public.stockly_plan(_empresa);
  if _plan.limite_ventas_mes is not null then
    _ventas_mes := (public.stockly_uso_plan(_empresa)->>'ventas_mes')::int;
    if _ventas_mes >= _plan.limite_ventas_mes then
      raise exception 'Llegaste al límite de % ventas del mes de tu plan %. Mejora tu plan para seguir vendiendo.',
        _plan.limite_ventas_mes, _plan.nombre;
    end if;
  end if;

  -- Consecutivo: bloquea la fila para que dos cajas no tomen el mismo número.
  select * into _cfg from public.config_facturacion where id_empresa = _empresa for update;
  if not found then
    perform public.stockly_inicializar_empresa(_empresa);
    select * into _cfg from public.config_facturacion where id_empresa = _empresa for update;
  end if;
  _numero := _cfg.consecutivo + 1;
  if _cfg.rango_hasta is not null and _numero > _cfg.rango_hasta then
    raise exception 'Se agotó el rango de numeración autorizado (%-%)', _cfg.rango_desde, _cfg.rango_hasta;
  end if;
  update public.config_facturacion set consecutivo = _numero, updated_at = now() where id_empresa = _empresa;

  insert into public.ventas (id_empresa, id_bodega, id_cliente, id_usuario, prefijo, numero, canal, metodo_pago, estado, nota)
  values (_empresa, _bodega, nullif(_venta->>'id_cliente', '')::bigint, _usuario, _cfg.prefijo, _numero,
          coalesce(_venta->>'canal', 'mostrador'), coalesce(_venta->>'metodo_pago', 'efectivo'),
          coalesce(_venta->>'estado', 'pagada'), _venta->>'nota')
  returning id into _id_venta;

  for _item in select * from jsonb_array_elements(_venta->'items') loop
    select id, descripcion into _producto from public.productos
     where id = (_item->>'id_producto')::bigint and id_empresa = _empresa;
    if not found then raise exception 'Producto no válido'; end if;

    _cantidad := (_item->>'cantidad')::numeric;
    _precio := (_item->>'precio_unitario')::numeric;
    _desc := coalesce((_item->>'descuento')::numeric, 0);
    _iva := coalesce((_item->>'iva')::numeric, 0);
    if _cantidad is null or _cantidad <= 0 then raise exception 'Cantidad no válida para %', _producto.descripcion; end if;
    if _precio is null or _precio < 0 or _desc < 0 or _iva < 0 then
      raise exception 'Precio o descuento no válido para %', _producto.descripcion;
    end if;
    if public.stockly_disponible(_bodega, _producto.id) < _cantidad then
      raise exception 'Stock insuficiente de % en esta bodega (disponible: %)',
        _producto.descripcion, trim_scale(public.stockly_disponible(_bodega, _producto.id));
    end if;

    _base := round(_cantidad * _precio - _desc, 2);
    if _base < 0 then raise exception 'El descuento de % supera el valor del producto', _producto.descripcion; end if;
    _subtotal := _subtotal + _cantidad * _precio;
    _descuento := _descuento + _desc;
    _impuesto := _impuesto + round(_base * _iva / 100, 2);

    insert into public.detalle_venta (id_venta, id_producto, descripcion, cantidad, precio_unitario, descuento, iva, total)
    values (_id_venta, _producto.id, _producto.descripcion, _cantidad, _precio, _desc, _iva,
            _base + round(_base * _iva / 100, 2));

    insert into public.kardex (fecha, tipo, id_usuario, cantidad, detalle, id_empresa, id_producto, id_bodega)
    values (now(), 'Salida', _usuario, _cantidad, 'Venta ' || _cfg.prefijo || '-' || _numero, _empresa, _producto.id, _bodega);
  end loop;

  update public.ventas
     set subtotal = round(_subtotal, 2), descuento = round(_descuento, 2), impuesto = round(_impuesto, 2),
         total = round(_subtotal - _descuento + _impuesto, 2)
   where id = _id_venta;

  insert into public.facturas (id_venta, id_empresa, prefijo, numero, tipo, estado_dian)
  values (_id_venta, _empresa, _cfg.prefijo, _numero,
          case when _cfg.electronica_activa then 'electronica' else 'interna' end,
          case when _cfg.electronica_activa then 'pendiente' else 'no_aplica' end);

  insert into public.notificaciones (id_empresa, tipo, titulo, mensaje, enlace)
  values (_empresa, 'venta', 'Nueva venta ' || _cfg.prefijo || '-' || _numero,
          jsonb_array_length(_venta->'items') || ' producto(s) · ' || coalesce(_venta->>'canal', 'mostrador'),
          '/ventas/facturas');

  return jsonb_build_object('id', _id_venta, 'prefijo', _cfg.prefijo, 'numero', _numero,
                            'total', round(_subtotal - _descuento + _impuesto, 2));
end $$;

create or replace function public.anular_venta(_id_venta bigint, _motivo text default null)
returns void
language plpgsql security definer set search_path = public
as $$
declare
  _v public.ventas;
  _d record;
begin
  select * into _v from public.ventas where id = _id_venta for update;
  if not found or not public.stockly_es_miembro(_v.id_empresa) then raise exception 'Venta no encontrada'; end if;
  if _v.estado = 'anulada' then raise exception 'La venta ya está anulada'; end if;

  for _d in select * from public.detalle_venta where id_venta = _id_venta and id_producto is not null loop
    insert into public.kardex (fecha, tipo, id_usuario, cantidad, detalle, id_empresa, id_producto, id_bodega)
    values (now(), 'Entrada', public.stockly_id_usuario(), _d.cantidad,
            'Anulación ' || _v.prefijo || '-' || _v.numero, _v.id_empresa, _d.id_producto, _v.id_bodega);
  end loop;

  update public.ventas set estado = 'anulada', nota = concat_ws(' · ', nota, 'Anulada: ' || _motivo) where id = _id_venta;
  update public.facturas set estado = 'anulada' where id_venta = _id_venta;
end $$;

-- ---------------------------------------------------------------------
-- Órdenes de compra
-- ---------------------------------------------------------------------
-- _orden: { id_empresa, id_proveedor?, id_bodega?, fecha_esperada?, nota?, creada_por?,
--           items: [{ id_producto, cantidad, costo_unitario? }] }
create or replace function public.crear_orden_compra(_orden jsonb)
returns jsonb
language plpgsql security definer set search_path = public
as $$
declare
  _empresa bigint := (_orden->>'id_empresa')::bigint;
  _bodega bigint := coalesce(nullif(_orden->>'id_bodega', '')::bigint, public.stockly_bodega_principal(_empresa));
  _id bigint;
  _numero int;
  _item jsonb;
  _p record;
  _cantidad numeric;
  _costo numeric;
begin
  if not public.stockly_es_miembro(_empresa) then raise exception 'Sin acceso a esta empresa'; end if;
  if not exists (select 1 from public.bodegas where id = _bodega and id_empresa = _empresa) then
    raise exception 'Bodega no válida';
  end if;
  if jsonb_array_length(coalesce(_orden->'items', '[]'::jsonb)) = 0 then raise exception 'La orden no tiene productos'; end if;

  perform pg_advisory_xact_lock(hashtext('orden_compra_' || _empresa));
  select coalesce(max(numero), 0) + 1 into _numero from public.ordenes_compra where id_empresa = _empresa;

  insert into public.ordenes_compra (id_empresa, id_proveedor, id_bodega, numero, fecha_esperada, nota, creada_por, id_usuario)
  values (_empresa, nullif(_orden->>'id_proveedor', '')::bigint, _bodega, _numero,
          nullif(_orden->>'fecha_esperada', '')::date, _orden->>'nota',
          coalesce(_orden->>'creada_por', 'usuario'), public.stockly_id_usuario())
  returning id into _id;

  for _item in select * from jsonb_array_elements(_orden->'items') loop
    select id, descripcion, preciocompra into _p from public.productos
     where id = (_item->>'id_producto')::bigint and id_empresa = _empresa;
    if not found then raise exception 'Producto no válido'; end if;
    _cantidad := (_item->>'cantidad')::numeric;
    _costo := coalesce((_item->>'costo_unitario')::numeric, _p.preciocompra, 0);
    if _cantidad is null or _cantidad <= 0 then raise exception 'Cantidad no válida para %', _p.descripcion; end if;
    insert into public.detalle_orden_compra (id_orden, id_producto, descripcion, cantidad, costo_unitario, total)
    values (_id, _p.id, _p.descripcion, _cantidad, _costo, round(_cantidad * _costo, 2));
  end loop;

  update public.ordenes_compra
     set total = (select coalesce(sum(total), 0) from public.detalle_orden_compra where id_orden = _id)
   where id = _id;

  return jsonb_build_object('id', _id, 'numero', _numero);
end $$;

create or replace function public.recibir_orden_compra(_id_orden bigint)
returns void
language plpgsql security definer set search_path = public
as $$
declare
  _o public.ordenes_compra;
  _d record;
  _unidades numeric := 0;
begin
  select * into _o from public.ordenes_compra where id = _id_orden for update;
  if not found or not public.stockly_es_miembro(_o.id_empresa) then raise exception 'Orden no encontrada'; end if;
  if _o.estado in ('recibida', 'cancelada') then raise exception 'La orden ya está %', _o.estado; end if;

  for _d in select * from public.detalle_orden_compra where id_orden = _id_orden loop
    insert into public.kardex (fecha, tipo, id_usuario, cantidad, detalle, id_empresa, id_producto, id_bodega)
    values (now(), 'Entrada', public.stockly_id_usuario(), _d.cantidad, 'Orden de compra OC-' || _o.numero,
            _o.id_empresa, _d.id_producto, _o.id_bodega);
    _unidades := _unidades + _d.cantidad;
  end loop;

  update public.ordenes_compra set estado = 'recibida', recibida_en = now() where id = _id_orden;

  insert into public.notificaciones (id_empresa, tipo, titulo, mensaje, enlace)
  values (_o.id_empresa, 'compra', 'Llegó el pedido OC-' || _o.numero,
          trim_scale(_unidades) || ' unidades · ' || (select nombre from public.bodegas where id = _o.id_bodega), '/compras');
end $$;

