insert into public.permisos (id_usuario, idmodulo)
select u.id, m.id
from public."Usuarios" u
cross join public.modulos m
where lower(coalesce(u.tipouser, '')) in ('dueño', 'administrador', 'admin')
  and m.nombre in ('Ventas', 'Bodegas', 'Compras', 'Clientes', 'Proveedores', 'Suscripción', 'Facturación')
  and not exists (select 1 from public.permisos p where p.id_usuario = u.id and p.idmodulo = m.id);

