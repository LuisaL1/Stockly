  id_bodega bigint not null references public.bodegas(id) on delete cascade,
  id_producto bigint not null references public.productos(id) on delete cascade,
  cantidad numeric(14, 3) not null default 0 check (cantidad >= 0),
  primary key (id_bodega, id_producto)
);

