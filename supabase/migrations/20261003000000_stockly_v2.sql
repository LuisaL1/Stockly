-- Datos iniciales por empresa (existentes y nuevas)
-- ---------------------------------------------------------------------
create or replace function public.stockly_inicializar_empresa(_id_empresa bigint)
returns void
language plpgsql security definer set search_path = public
as $$
begin
  insert into public.bodegas (id_empresa, nombre, tipo)
  select _id_empresa, 'Bodega principal', 'principal'
  where not exists (select 1 from public.bodegas where id_empresa = _id_empresa and tipo = 'principal');

  insert into public.stockly_suscripciones (id_empresa) values (_id_empresa) on conflict (id_empresa) do nothing;

  insert into public.config_facturacion (id_empresa, razon_social)
  select _id_empresa, e.nombre from public."Empresa" e where e.id = _id_empresa
  on conflict (id_empresa) do nothing;
end $$;

create or replace function public.tg_empresa_inicializar()
returns trigger language plpgsql security definer set search_path = public
as $$
begin
  perform public.stockly_inicializar_empresa(new.id);
  return new;
end $$;

drop trigger if exists empresa_inicializar on public."Empresa";
create trigger empresa_inicializar after insert on public."Empresa"
  for each row execute function public.tg_empresa_inicializar();

select public.stockly_inicializar_empresa(id) from public."Empresa";

