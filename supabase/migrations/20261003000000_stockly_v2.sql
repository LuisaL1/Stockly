-- ---------------------------------------------------------------------
-- Seguridad (RLS): cada empresa solo ve lo suyo
-- ---------------------------------------------------------------------
do $$
declare t text;
begin
  foreach t in array array['stockly_suscripciones', 'historial_suscripcion', 'bodegas', 'traslados', 'clientes',
                           'proveedores', 'config_facturacion', 'ventas', 'facturas', 'ordenes_compra',
                           'notificaciones', 'novandra_uso']
  loop
    execute format('alter table public.%I enable row level security', t);
    execute format('drop policy if exists "miembros %1$s" on public.%1$I', t);
    execute format(
      'create policy "miembros %1$s" on public.%1$I for all
         using (public.stockly_es_miembro(id_empresa))
         with check (public.stockly_es_miembro(id_empresa))', t);
  end loop;
end $$;

alter table public.stockly_planes enable row level security;
drop policy if exists "stockly_planes visibles" on public.stockly_planes;
create policy "stockly_planes visibles" on public.stockly_planes for select using (true);

alter table public.stock_bodega enable row level security;
drop policy if exists "miembros stock_bodega" on public.stock_bodega;
create policy "miembros stock_bodega" on public.stock_bodega for all
  using (exists (select 1 from public.bodegas b where b.id = id_bodega and public.stockly_es_miembro(b.id_empresa)))
  with check (exists (select 1 from public.bodegas b where b.id = id_bodega and public.stockly_es_miembro(b.id_empresa)));

alter table public.detalle_venta enable row level security;
drop policy if exists "miembros detalle_venta" on public.detalle_venta;
create policy "miembros detalle_venta" on public.detalle_venta for all
  using (exists (select 1 from public.ventas v where v.id = id_venta and public.stockly_es_miembro(v.id_empresa)))
  with check (exists (select 1 from public.ventas v where v.id = id_venta and public.stockly_es_miembro(v.id_empresa)));

alter table public.detalle_orden_compra enable row level security;
drop policy if exists "miembros detalle_orden_compra" on public.detalle_orden_compra;
