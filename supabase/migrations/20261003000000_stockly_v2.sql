create or replace view public.v_stock_bodega
with (security_invoker = true) as
select b.id as id_bodega, b.id_empresa, b.nombre as bodega, b.tipo,
       p.id as id_producto, p.descripcion, p.stock_minimo, p.precioventa, p.preciocompra,
       case when b.tipo = 'principal'
            then greatest(p.stock - coalesce((
                   select sum(sb.cantidad) from public.stock_bodega sb
                   join public.bodegas o on o.id = sb.id_bodega
                   where sb.id_producto = p.id and o.tipo <> 'principal'), 0), 0)
            else coalesce(sb.cantidad, 0)
       end as cantidad
from public.bodegas b
join public.productos p on p.id_empresa = b.id_empresa
left join public.stock_bodega sb on sb.id_bodega = b.id and sb.id_producto = p.id;

create or replace function public.stockly_disponible(_id_bodega bigint, _id_producto bigint)
returns numeric
language sql stable security definer set search_path = public
as $$
  select coalesce((select cantidad from public.v_stock_bodega
                   where id_bodega = _id_bodega and id_producto = _id_producto), 0)
$$;

create or replace function public.stockly_bodega_principal(_id_empresa bigint)
returns bigint
language sql stable security definer set search_path = public
as $$
  select id from public.bodegas where id_empresa = _id_empresa and tipo = 'principal' limit 1
$$;

