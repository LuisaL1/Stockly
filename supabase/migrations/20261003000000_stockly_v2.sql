-- Límites del plan
-- ---------------------------------------------------------------------
create or replace function public.stockly_plan(_id_empresa bigint)
returns public.stockly_planes
language sql stable security definer set search_path = public
as $$
  select * from public.stockly_planes
  where id = coalesce((select id_plan from public.stockly_suscripciones where id_empresa = _id_empresa), 'basico')
$$;

create or replace function public.tg_bodegas_limite()
returns trigger language plpgsql security definer set search_path = public
as $$
declare _limite int;
begin
  _limite := (public.stockly_plan(new.id_empresa)).limite_bodegas;
  if _limite is not null and (select count(*) from public.bodegas where id_empresa = new.id_empresa) >= _limite then
    raise exception 'Tu plan permite % bodega(s). Mejora tu plan para agregar más.', _limite
      using errcode = 'P0001';
  end if;
  return new;
end $$;

drop trigger if exists bodegas_limite on public.bodegas;
create trigger bodegas_limite before insert on public.bodegas
  for each row when (new.tipo <> 'principal') execute function public.tg_bodegas_limite();

-- Uso actual frente a los límites, para la página del plan y para Novandra.
create or replace function public.stockly_uso_plan(_id_empresa bigint)
returns jsonb
language plpgsql stable security definer set search_path = public
as $$
declare _inicio_mes timestamptz := date_trunc('month', now() at time zone 'America/Bogota') at time zone 'America/Bogota';
begin
  if not public.stockly_es_miembro(_id_empresa) then
    raise exception 'Sin acceso a esta empresa';
  end if;
  return jsonb_build_object(
    'productos', (select count(*) from public.productos where id_empresa = _id_empresa),
    'bodegas', (select count(*) from public.bodegas where id_empresa = _id_empresa),
    'usuarios', (select count(*) from public.asignarempresa where id_empresa = _id_empresa),
    'ventas_mes', (select count(*) from public.ventas where id_empresa = _id_empresa
                     and fecha >= _inicio_mes and estado <> 'anulada'),
    'novandra_mes', (select count(*) from public.novandra_uso where id_empresa = _id_empresa and fecha >= _inicio_mes)
  );
end $$;

create or replace function public.cambiar_plan(_id_empresa bigint, _id_plan text, _ciclo text default 'mensual')
returns jsonb
language plpgsql security definer set search_path = public
as $$
declare
  _plan public.stockly_planes;
  _uso jsonb;
  _anterior text;
begin
  if not public.stockly_es_admin(_id_empresa) then
    raise exception 'Solo el dueño o un administrador puede cambiar el plan';
  end if;
  select * into _plan from public.stockly_planes where id = _id_plan;
  if not found then raise exception 'Plan no válido'; end if;
  if _ciclo not in ('mensual', 'anual') then raise exception 'Ciclo no válido'; end if;

  _uso := public.stockly_uso_plan(_id_empresa);
  if _plan.limite_productos is not null and (_uso->>'productos')::int > _plan.limite_productos then
    raise exception 'Tienes % productos y el plan % permite %.', _uso->>'productos', _plan.nombre, _plan.limite_productos;
  end if;
  if _plan.limite_bodegas is not null and (_uso->>'bodegas')::int > _plan.limite_bodegas then
    raise exception 'Tienes % bodegas y el plan % permite %.', _uso->>'bodegas', _plan.nombre, _plan.limite_bodegas;
  end if;
  if _plan.limite_usuarios is not null and (_uso->>'usuarios')::int > _plan.limite_usuarios then
    raise exception 'Tienes % usuarios y el plan % permite %.', _uso->>'usuarios', _plan.nombre, _plan.limite_usuarios;
  end if;

  select id_plan into _anterior from public.stockly_suscripciones where id_empresa = _id_empresa;
  update public.stockly_suscripciones
     set id_plan = _id_plan, ciclo = _ciclo, estado = 'activa', inicio = now(),
         renovacion = now() + case when _ciclo = 'anual' then interval '1 year' else interval '1 month' end
   where id_empresa = _id_empresa;

  insert into public.historial_suscripcion (id_empresa, plan_anterior, plan_nuevo, ciclo, id_usuario)
  values (_id_empresa, _anterior, _id_plan, _ciclo, public.stockly_id_usuario());

  insert into public.notificaciones (id_empresa, tipo, titulo, mensaje, enlace)
  values (_id_empresa, 'plan', 'Plan actualizado a ' || _plan.nombre,
          'Facturación ' || _ciclo || '. Los nuevos límites ya están activos.', '/configurar/plan');

  return jsonb_build_object('plan', _id_plan, 'ciclo', _ciclo);
end $$;

-- ---------------------------------------------------------------------
-- Kardex por bodega
-- ---------------------------------------------------------------------
create or replace function public.tg_kardex_bodega()
returns trigger language plpgsql security definer set search_path = public
as $$
declare
  _fila record;
  _signo int;
  _tipo text;
begin
  if tg_when = 'BEFORE' then
    if new.id_bodega is null then
      new.id_bodega := public.stockly_bodega_principal(new.id_empresa);
    end if;
    return new;
  end if;

  if tg_op = 'DELETE' then
    _fila := old;
  else
    _fila := new;
  end if;
  -- La bodega principal se calcula a partir del stock total: no hay nada que mover.
  if _fila.id_bodega is null
     or (select tipo from public.bodegas where id = _fila.id_bodega) = 'principal' then
    return null;
  end if;

  _tipo := lower(coalesce(_fila.tipo, ''));
  _signo := case when _tipo = 'salida' then -1 else 1 end;
  if tg_op = 'DELETE' then _signo := -_signo; end if;

  insert into public.stock_bodega (id_bodega, id_producto, cantidad)
  values (_fila.id_bodega, _fila.id_producto, greatest(_signo * _fila.cantidad, 0))
  on conflict (id_bodega, id_producto)
  do update set cantidad = greatest(public.stock_bodega.cantidad + _signo * _fila.cantidad, 0);
  return null;
end $$;

drop trigger if exists kardex_bodega_antes on public.kardex;
create trigger kardex_bodega_antes before insert on public.kardex
  for each row execute function public.tg_kardex_bodega();
