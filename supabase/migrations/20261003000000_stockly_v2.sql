-- =====================================================================
-- Stockly v2: planes y suscripción, bodegas, clientes, proveedores,
-- ventas y facturación, órdenes de compra, notificaciones y Novandra.
--
-- Los planes van en "stockly_planes" y "stockly_suscripciones" para no
-- chocar con tablas "planes"/"suscripciones" que ya existían en la base.
--
-- Se ejecuta sobre la base existente (Empresa, Usuarios, asignarempresa,
-- modulos, permisos, productos, kardex). Es idempotente: se puede volver
-- a ejecutar sin duplicar datos.
--
-- Supuesto importante: el stock total de "productos" lo mantiene el
-- trigger que ya existe sobre "kardex" (el mismo que usa la página Kardex).
-- Aquí solo se registra en kardex y se lleva la distribución por bodega.
-- =====================================================================

-- ---------------------------------------------------------------------
-- Utilidades de acceso
-- ---------------------------------------------------------------------
create or replace function public.stockly_id_usuario()
returns bigint
language sql stable security definer set search_path = public
as $$
  select id from "Usuarios" where idauth::text = auth.uid()::text limit 1
$$;

create or replace function public.stockly_es_miembro(_id_empresa bigint)
returns boolean
language sql stable security definer set search_path = public
as $$
  select exists (
    select 1 from asignarempresa a
    where a.id_empresa = _id_empresa and a.id_usuario = public.stockly_id_usuario()
  )
$$;

create or replace function public.stockly_es_admin(_id_empresa bigint)
returns boolean
language sql stable security definer set search_path = public
as $$
  select public.stockly_es_miembro(_id_empresa) and exists (
    select 1 from "Usuarios" u
    where u.id = public.stockly_id_usuario()
      and lower(coalesce(u.tipouser, '')) in ('dueño', 'administrador', 'admin')
  )
$$;

