-- Complementos comprados: cada compra (o renovación) es una fila con su vigencia.
create table if not exists public.empresa_complementos (
  id bigint generated by default as identity primary key,
  id_empresa bigint not null references public."Empresa"(id) on delete cascade,
  id_complemento text not null references public.stockly_complementos(id),
  cantidad int not null check (cantidad > 0),
  desde timestamptz not null default now(),
  hasta timestamptz not null,
  id_pago bigint,
  created_at timestamptz not null default now()
);
create index if not exists empresa_complementos_vigentes on public.empresa_complementos (id_empresa, hasta);
alter table public.empresa_complementos enable row level security;
drop policy if exists "miembros ven sus complementos" on public.empresa_complementos;
create policy "miembros ven sus complementos" on public.empresa_complementos for select using (public.stockly_es_miembro(id_empresa));

