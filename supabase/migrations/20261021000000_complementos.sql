-- =====================================================================
-- Stockly: complementos (capacidad adicional que se compra sobre el plan).
--
-- Una empresa con plan pagado vigente (Pro o Enterprise) puede comprar, por ejemplo,
-- usuarios, sedes o productos adicionales sin cambiar de plan. Reglas:
--  * Cada complemento suma una cantidad fija a uno o más límites del plan.
--  * Se cobra proporcional a los días que le quedan al plan y vence con él.
--  * Al renovar el mismo plan, los complementos vigentes se renuevan con él
--    (opcional), por el mismo ciclo (anual = 10 meses, como los planes).
--  * Tiene tope de unidades por empresa (nada ilimitado) y cuesta más por
--    unidad que lo que trae incluido el plan.
-- stockly_plan() devuelve el plan efectivo con los complementos sumados, así que
-- todos los topes del servidor (triggers, ventas, Novandra, invitaciones) los cuentan.
-- Requiere 20261020000000_limites_planes.sql. Se puede ejecutar varias veces.
-- =====================================================================

create table if not exists public.stockly_complementos (
  id text primary key,
  nombre text not null,
  descripcion text not null,
  incrementos jsonb not null,           -- por unidad, p. ej. {"limite_usuarios": 1}
  precio_mensual numeric(14, 2) not null,
  max_unidades int not null,            -- tope de unidades vigentes por empresa
  requiere text,                        -- ajuste global que debe estar activo (p. ej. novandra_ia_disponible)
  orden int not null default 0,
  activo boolean not null default true
);
alter table public.stockly_complementos enable row level security;
drop policy if exists "todos ven los complementos" on public.stockly_complementos;
create policy "todos ven los complementos" on public.stockly_complementos for select using (true);

